-- =============================================================
-- Esquema do banco de dados - API Concessionária (PostgreSQL)
-- =============================================================
-- Se NÃO estiver usando o docker-compose, crie o banco antes:
--   CREATE DATABASE concessionaria;
-- e depois execute este arquivo conectado a ele:
--   psql -U postgres -d concessionaria -f database/01-schema.sql
-- =============================================================

CREATE TABLE IF NOT EXISTS carros (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca           VARCHAR(50)  NOT NULL,
    modelo          VARCHAR(100) NOT NULL,
    ano_fabricacao  INTEGER      NOT NULL,
    ano_modelo      INTEGER      NOT NULL,
    motorizacao     VARCHAR(50)  NOT NULL
);
